import { Router } from 'express';
import { requireAuth } from '../../middlewares/auth.middleware';
import { requireRole } from '../../middlewares/role.middleware';
import { validateBody, validateParams, validateQuery } from '../../middlewares/validate.middleware';
import * as controller from './categorias.controller';
import { actualizarCategoriaSchema, crearCategoriaSchema, categoriaParamsSchema, categoriasQuerySchema } from './categorias.schema';
import horariosRoutes from '../horarios/horarios.routes';
const router = Router();
router.use(requireAuth);
router.use('/:id/horarios', horariosRoutes);
router.get('/', validateQuery(categoriasQuerySchema), controller.list);
router.get('/:id', validateParams(categoriaParamsSchema), controller.getById);
router.post('/', requireRole('ADM'), validateBody(crearCategoriaSchema), controller.create);
router.put('/:id', requireRole('ADM'), validateParams(categoriaParamsSchema), validateBody(actualizarCategoriaSchema), controller.update);
router.delete('/:id', requireRole('ADM'), validateParams(categoriaParamsSchema), controller.remove);
export default router;
