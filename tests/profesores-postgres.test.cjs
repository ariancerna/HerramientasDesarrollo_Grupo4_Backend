const { test } = require('node:test');
const assert = require('node:assert/strict');
const { postgresFixture } = require('./helpers/postgres-fixture.cjs');
const id = '11111111-1111-4111-8111-111111111111';
const missing = '99999999-9999-4999-8999-999999999999';
test('PRF Postgres mantiene perfil y cuenta atomicos, reemplaza asignaciones y protege RPC', async (t) => {
  const db = await postgresFixture(t, ['_profesores_transacciones.sql']);
  const { rows: [sede] } = await db.query("INSERT INTO sedes(nombre) VALUES ('Sede 1') RETURNING id");
  const { rows: [cat] } = await db.query("INSERT INTO categorias(nombre) VALUES ('Sub-12') RETURNING id");
  const args = [id, 'Profesor', 'profesor', 'profesor@example.invalid', sede.id, [cat.id]];
  await assert.rejects(db.query('SELECT crear_profesor($1,$2,$3,$4,$5,$6::uuid[])', [...args.slice(0, 5), [missing]]), { code: '23503' });
  assert.equal((await db.query('SELECT * FROM profesores')).rows.length, 0);
  assert.equal((await db.query('SELECT * FROM usuarios')).rows.length, 0);
  const { rows: [created] } = await db.query('SELECT crear_profesor($1,$2,$3,$4,$5,$6::uuid[]) AS data', args);
  assert.deepEqual(created.data.categoriaIds, [cat.id]);
  assert.equal(created.data.password, undefined);
  await assert.rejects(db.query('SELECT asignar_categorias_profesor($1,$2::uuid[])', [id, [missing]]), { code: '23503' });
  assert.equal((await db.query('SELECT * FROM profesores_categorias')).rows.length, 1);
  await db.query('SELECT actualizar_profesor($1,$2::jsonb)', [id, JSON.stringify({ nombre: 'Actualizado', usuario: 'nuevo' })]);
  assert.equal((await db.query('SELECT nombre FROM profesores')).rows[0].nombre, 'Actualizado');
  assert.equal((await db.query('SELECT usuario,nombre FROM usuarios')).rows[0].usuario, 'nuevo');
  await db.exec('SET ROLE anon');
  await assert.rejects(db.query('SELECT profesor_json($1)', [id]), { code: '42501' });
  await assert.rejects(db.query('SELECT * FROM profesores_auth_pendientes'), { code: '42501' });
  await db.exec('RESET ROLE');
  await db.query('SELECT asignar_categorias_profesor($1,$2::uuid[])', [id, []]);
  assert.equal((await db.query('SELECT * FROM profesores_categorias')).rows.length, 0);
  await db.query('SELECT eliminar_profesor($1)', [id]);
  assert.equal((await db.query('SELECT * FROM usuarios')).rows.length, 0);
  assert.equal((await db.query('SELECT * FROM profesores_auth_pendientes')).rows[0].profesor_id, id);
  assert.equal((await db.query('SELECT eliminar_profesor($1) AS removed', [id])).rows[0].removed, true);
  assert.equal((await db.query('SELECT eliminar_profesor($1) AS removed', [missing])).rows[0].removed, false);
});
test('PRF Postgres revierte eliminacion si el profesor tiene evaluaciones', async (t) => {
  const db = await postgresFixture(t, ['_profesores_transacciones.sql']);
  const { rows: [sede] } = await db.query("INSERT INTO sedes(nombre) VALUES ('Sede 1') RETURNING id");
  await db.query('SELECT crear_profesor($1,$2,$3,$4,$5,$6::uuid[])', [id, 'Profesor', 'profesor', 'profesor@example.invalid', sede.id, []]);
  const { rows: [alu] } = await db.query("INSERT INTO alumnos(dni,nombres,apellidos) VALUES ('12345678','Alumno','Prueba') RETURNING id");
  await db.query("INSERT INTO evaluaciones(alumno_id,profesor_id,fecha,observaciones) VALUES ($1,$2,'2026-10-12','Prueba')", [alu.id, id]);
  await assert.rejects(db.query('SELECT eliminar_profesor($1)', [id]), { code: '23503' });
  assert.equal((await db.query('SELECT * FROM usuarios')).rows.length, 1);
  assert.equal((await db.query('SELECT * FROM profesores')).rows.length, 1);
  assert.equal((await db.query('SELECT * FROM profesores_auth_pendientes')).rows.length, 0);
});
